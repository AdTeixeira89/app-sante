/* ---------- Língua ativa ---------- */
function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && LANGS.some((l) => l.code === saved)) return saved;
  } catch (e) { /* armazenamento indisponível */ }
  const prefs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "en"]);
  for (const p of prefs) {
    const base = String(p).toLowerCase().split("-")[0];
    if (LANGS.some((l) => l.code === base)) return base;
  }
  return "en"; // língua de reserva para o resto do mundo
}

let currentLang = detectLang();

export function getLang() { return currentLang; }
export function getLocale() { return (LANGS.find((l) => l.code === currentLang) || LANGS[0]).locale; }

export function setLang(code) {
  if (!LANGS.some((l) => l.code === code)) return;
  currentLang = code;
  try { localStorage.setItem(LANG_KEY, code); } catch (e) { /* ignorar */ }
}

/* t("Texto em português {x}", { x: 1 }) → texto na língua ativa */
export function t(key, params) {
  let out = key;
  if (currentLang !== "pt") {
    const dict = TRANSLATIONS[currentLang];
    if (dict && Object.prototype.hasOwnProperty.call(dict, key)) out = dict[key];
  }
  if (params) {
    out = out.replace(/\{(\w+)\}/g, (m, name) => (params[name] != null ? String(params[name]) : m));
  }
  return out;
}

/* ---------- Tradução do HTML estático (texto e atributos) ----------
   Guarda o texto original em português no próprio elemento para poder mudar de língua sem recarregar. */
const ATTRS = ["placeholder", "aria-label", "title", "alt"];

function norm(s) { return s.replace(/\s+/g, " ").trim(); }

export function applyI18n(root = document.body) {
  document.documentElement.lang = currentLang;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const p = node.parentNode;
      if (!p || ["SCRIPT", "STYLE"].includes(p.nodeName)) return NodeFilter.FILTER_REJECT;
      return /\S/.test(node.nodeValue) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    if (node.__pt === undefined) node.__pt = node.nodeValue;
    const key = norm(node.__pt);
    const lead = node.__pt.match(/^\s*/)[0];
    const trail = node.__pt.match(/\s*$/)[0];
    node.nodeValue = lead + t(key) + trail;
  });

  root.querySelectorAll("*").forEach((el) => {
    ATTRS.forEach((a) => {
      if (!el.hasAttribute(a)) return;
      const store = "__pt_" + a;
      if (el[store] === undefined) el[store] = el.getAttribute(a);
      el.setAttribute(a, t(norm(el[store])));
    });
  });
}
